pub fn generate_hf_pose_script(req: &TrainingRequest, sp: &ScriptPaths) -> String {
    let bp = &req.backend_params;
    let weight_decay = bp
        .get("weight_decay")
        .and_then(|v| v.as_f64())
        .unwrap_or(1e-4);
    let heatmap_sigma = bp
        .get("heatmap_sigma")
        .and_then(|v| v.as_f64())
        .unwrap_or(2.0);
    let device = format_device(&req.device);

    format!(
        r#"#!/usr/bin/env python3
"""
HuggingFace Pose / Landmarks Training Script - Generated by Annotix
Backbone: {model_id}
"""
import sys
import json
import os

{header}
{preamble}

def main():
    import numpy as np
    import torch
    import torch.nn as nn
    from torch.utils.data import Dataset, DataLoader
    from PIL import Image
    import timm

    device = torch.device({device} if {device} != "" else ("cuda" if torch.cuda.is_available() else "cpu"))
    dataset_dir = DATASET_DIR
    output_dir = os.path.join(dataset_dir, "train_output")
    os.makedirs(output_dir, exist_ok=True)

    ENTRADA = {image_size}
    SALIDA = ENTRADA // 4  # resolución del heatmap
    SIGMA = {heatmap_sigma}

    class CocoKeypointDataset(Dataset):
        """Recorta cada instancia por su caja y genera un heatmap por keypoint."""

        def __init__(self, images_dir, ann_file):
            self.images_dir = images_dir
            datos, por_imagen = _cargar_coco(ann_file)
            self.imagenes = {{im["id"]: im for im in datos["images"]}}
            self.n_kp = 0
            for cat in datos.get("categories", []):
                self.n_kp = max(self.n_kp, len(cat.get("keypoints", []) or []))
            self.muestras = []
            for image_id, anns in por_imagen.items():
                for ann in anns:
                    kps = ann.get("keypoints") or []
                    if kps:
                        self.n_kp = max(self.n_kp, len(kps) // 3)
                        self.muestras.append((image_id, ann))
            if not self.muestras:
                raise RuntimeError(f"Sin keypoints utilizables en {{ann_file}}")

        def __len__(self):
            return len(self.muestras)

        def __getitem__(self, idx):
            image_id, ann = self.muestras[idx]
            info = self.imagenes[image_id]
            imagen = Image.open(os.path.join(self.images_dir, info["file_name"])).convert("RGB")

            x, y, w, h = ann.get("bbox", [0, 0, info["width"], info["height"]])
            w = max(w, 1.0)
            h = max(h, 1.0)
            recorte = imagen.crop((x, y, x + w, y + h)).resize((ENTRADA, ENTRADA))
            pixeles = torch.from_numpy(
                np.asarray(recorte, dtype=np.float32).transpose(2, 0, 1) / 255.0
            )

            kps = ann.get("keypoints") or []
            heatmaps = np.zeros((self.n_kp, SALIDA, SALIDA), dtype=np.float32)
            rejilla = np.arange(SALIDA, dtype=np.float32)
            for k in range(min(self.n_kp, len(kps) // 3)):
                kx, ky, visible = kps[3 * k], kps[3 * k + 1], kps[3 * k + 2]
                if visible <= 0:
                    continue
                cx = (kx - x) / w * SALIDA
                cy = (ky - y) / h * SALIDA
                if not (0 <= cx < SALIDA and 0 <= cy < SALIDA):
                    continue
                gx = np.exp(-((rejilla - cx) ** 2) / (2 * SIGMA ** 2))
                gy = np.exp(-((rejilla - cy) ** 2) / (2 * SIGMA ** 2))
                heatmaps[k] = np.outer(gy, gx)
            return pixeles, torch.from_numpy(heatmaps)

    train_ds = CocoKeypointDataset(IMAGES_TRAIN, ANN_TRAIN)
    val_ds = CocoKeypointDataset(IMAGES_VAL, ANN_VAL)
    n_kp = max(train_ds.n_kp, val_ds.n_kp, 1)
    print(f"train: {{len(train_ds)}} instancias · val: {{len(val_ds)}} · keypoints: {{n_kp}}", flush=True)

    _drop_last = len(train_ds) > {batch}
    train_loader = DataLoader(
        train_ds, batch_size={batch}, shuffle=True, num_workers={workers}, drop_last=_drop_last
    )
    val_loader = DataLoader(val_ds, batch_size=1, shuffle=False, num_workers={workers})

    # Backbone de timm + cabeza de heatmaps: es el esquema top-down clásico, sin
    # depender de mmpose (incompatible con torch 2.x).
    backbone = timm.create_model("{model_id}", pretrained=True, features_only=True)
    canales = backbone.feature_info.channels()[-1]

    class PoseNet(nn.Module):
        def __init__(self):
            super().__init__()
            self.backbone = backbone
            self.head = nn.Sequential(
                nn.Conv2d(canales, 256, 3, padding=1),
                nn.BatchNorm2d(256),
                nn.ReLU(inplace=True),
                nn.Conv2d(256, n_kp, 1),
            )

        def forward(self, x):
            rasgos = self.backbone(x)[-1]
            salida = self.head(rasgos)
            return nn.functional.interpolate(
                salida, size=(SALIDA, SALIDA), mode="bilinear", align_corners=False
            )

    model = PoseNet().to(device)
    criterio = nn.MSELoss()
    optimizer = torch.optim.AdamW(model.parameters(), lr={lr}, weight_decay={weight_decay})

    def error_de_keypoints(pred, objetivo):
        """Distancia media entre el máximo predicho y el real, normalizada."""
        b, k, h, w = pred.shape
        p = pred.reshape(b, k, -1).argmax(-1)
        t = objetivo.reshape(b, k, -1).argmax(-1)
        px, py = (p % w).float(), (p // w).float()
        tx, ty = (t % w).float(), (t // w).float()
        visible = objetivo.reshape(b, k, -1).max(-1).values > 0
        if visible.sum() == 0:
            return None
        dist = torch.sqrt((px - tx) ** 2 + (py - ty) ** 2) / float(w)
        return float(dist[visible].mean())

    mejor = None
    for epoch in range(1, {epochs} + 1):
        model.train()
        total = 0.0
        for pixeles, objetivo in train_loader:
            optimizer.zero_grad()
            salida = model(pixeles.to(device))
            perdida = criterio(salida, objetivo.to(device))
            perdida.backward()
            optimizer.step()
            total += float(perdida.item())
        perdida_train = total / max(len(train_loader), 1)

        model.eval()
        total_val = 0.0
        errores = []
        with torch.no_grad():
            for pixeles, objetivo in val_loader:
                objetivo = objetivo.to(device)
                salida = model(pixeles.to(device))
                total_val += float(criterio(salida, objetivo).item())
                err = error_de_keypoints(salida, objetivo)
                if err is not None:
                    errores.append(err)
        perdida_val = total_val / max(len(val_loader), 1)

        metricas = {{"trainLoss": perdida_train, "valLoss": perdida_val}}
        if errores:
            # Fracción de keypoints con error < 5% del lado: un PCK simplificado.
            metricas["keypointAP"] = float(sum(1.0 for e in errores if e < 0.05) / len(errores))
            metricas["mae"] = float(sum(errores) / len(errores))
        _emitir_epoca(epoch, {epochs}, metricas)

        if mejor is None or perdida_val < mejor:
            mejor = perdida_val
            torch.save(
                {{"state_dict": model.state_dict(), "num_keypoints": n_kp, "input_size": ENTRADA}},
                os.path.join(output_dir, "best.pth"),
            )

    torch.save(
        {{"state_dict": model.state_dict(), "num_keypoints": n_kp, "input_size": ENTRADA}},
        os.path.join(output_dir, "last.pth"),
    )

    try:
        model.eval()
        dummy = torch.randn(1, 3, ENTRADA, ENTRADA).to(device)
        torch.onnx.export(
            model, dummy, os.path.join(output_dir, "model.onnx"),
            opset_version=17, input_names=["input"], output_names=["heatmaps"],
        )
    except Exception as e:
        print(f"ONNX export failed: {{e}}", file=sys.stderr)

    _mejor = os.path.join(output_dir, "best.pth")
    _ultimo = os.path.join(output_dir, "last.pth")
    print("ANNOTIX_EVENT:" + json.dumps({{
        "type": "completed",
        "bestModelPath": _mejor if os.path.exists(_mejor) else _ultimo,
        "lastModelPath": _ultimo,
        "resultsDir": output_dir,
    }}), flush=True)

if __name__ == "__main__":
    main()
"#,
        header = sp.header,
        preamble = hf_coco_preamble(),
        model_id = req.model_id,
        device = device,
        epochs = req.epochs,
        batch = req.batch_size,
        workers = req.workers,
        lr = req.lr,
        weight_decay = weight_decay,
        image_size = req.image_size,
        heatmap_sigma = heatmap_sigma,
    )
}

