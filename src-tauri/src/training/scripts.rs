// ─── STUMPY Script ───────────────────────────────────────────────────────────

pub fn generate_stumpy_script(req: &TrainingRequest, sp: &ScriptPaths) -> String {
    let bp = &req.backend_params;
    let model_id = &req.model_id; // e.g. "STUMP", "STUMPED", "GPU_STUMP", "MSTUMP"
    let window_size = bp.get("window_size").and_then(|v| v.as_u64()).unwrap_or(50);
    let normalize = bp
        .get("normalize")
        .and_then(|v| v.as_bool())
        .unwrap_or(true);
    let threshold_percentile = bp
        .get("threshold_percentile")
        .and_then(|v| v.as_f64())
        .unwrap_or(95.0);

    format!(
        r#"#!/usr/bin/env python3
"""
STUMPY Matrix Profile Analysis Script - Generated by Annotix
Method: {model_id}
"""
import sys
import json
import math
import os
import numpy as np

{header}

def _clave_modelo(valor, prefijo):
    """Normaliza el id del catálogo al nombre corto del dispatch.

    El catálogo expone ids como `pyod-iforest` o `pypots-saits`, y los scripts
    comparaban contra `IForest` o `SAITS`: ninguna comparación acertaba y todos los
    proyectos acababan entrenando el modelo del `else`. Elegir modelo en la UI no
    tenía ningún efecto.
    """
    clave = valor.lower().replace("-", "_")
    return clave[len(prefijo):] if clave.startswith(prefijo) else clave


def main():
    import stumpy

    dataset_dir = DATASET_DIR
    output_dir = os.path.join(dataset_dir, "train_output")
    os.makedirs(output_dir, exist_ok=True)

    method = _clave_modelo("{model_id}", "stumpy_")
    window_size = {window_size}
    normalize = {normalize}

    def _finito(valor):
        """Convierte inf/NaN en None: json.dumps los escribe como `Infinity`/`NaN`,
        que no son JSON válido, y el runner descarta el evento completo."""
        try:
            v = float(valor)
        except (TypeError, ValueError):
            return None
        return v if math.isfinite(v) else None

    # Serie declarada por el preparador (ver training/contract.rs). stumpy exige
    # float64: con float32 aborta con "dtype expected but found float32".
    ts = np.load(X_TRAIN).squeeze().astype(np.float64)

    # Emit start
    event = {{
        "type": "epoch",
        "epoch": 0,
        "totalEpochs": 1,
        "progress": 0.0,
        "metrics": {{"status": "computing_matrix_profile", "dataLength": int(ts.shape[0] if ts.ndim == 1 else ts.shape[-1])}},
    }}
    print("ANNOTIX_EVENT:" + json.dumps(event), flush=True)

    # Compute matrix profile
    if ts.ndim == 1:
        if method == "gpu_stump":
            try:
                mp = stumpy.gpu_stump(ts, m=window_size, normalize=normalize)
            except Exception:
                mp = stumpy.stump(ts, m=window_size, normalize=normalize)
        elif method == "stumped":
            mp = stumpy.stumped(None, ts, m=window_size, normalize=normalize)
        else:  # STUMP
            mp = stumpy.stump(ts, m=window_size, normalize=normalize)

        profile = mp[:, 0].astype(np.float64)
        indices = mp[:, 1].astype(np.int64)
    else:
        # Multidimensional: use MSTUMP
        if ts.ndim == 2 and ts.shape[0] > ts.shape[1]:
            ts = ts.T  # Ensure (n_dims, n_timepoints)
        mps, mpi = stumpy.mstump(ts, m=window_size, normalize=normalize)
        profile = mps[0]  # 1D profile for first dimension
        indices = mpi[0]

    # stumpy marca con `inf` las posiciones sin vecino válido (zona de exclusión):
    # las estadísticas se calculan sobre los valores finitos, no sobre el array
    # entero, que daría media e inf y desvío NaN.
    finitos = profile[np.isfinite(profile)]
    if finitos.size == 0:
        print("ANNOTIX_EVENT:" + json.dumps({{
            "type": "error",
            "message": "El perfil matricial no tiene valores finitos: serie demasiado corta para esta ventana",
        }}), flush=True)
        sys.exit(1)

    threshold = float(np.percentile(finitos, {threshold_percentile}))
    anomalies = np.where(np.isfinite(profile) & (profile > threshold))[0]

    metrics = {{
        "profileMean": _finito(np.mean(finitos)),
        "profileStd": _finito(np.std(finitos)),
        "profileMin": _finito(np.min(finitos)),
        "profileMax": _finito(np.max(finitos)),
        "threshold": _finito(threshold),
        "numAnomalies": int(len(anomalies)),
        "anomalyRatio": float(len(anomalies) / finitos.size),
    }}

    # Emit completion
    event = {{
        "type": "epoch",
        "epoch": 1,
        "totalEpochs": 1,
        "progress": 100.0,
        "metrics": metrics,
    }}
    print("ANNOTIX_EVENT:" + json.dumps(event), flush=True)

    # Save results
    np.save(os.path.join(output_dir, "matrix_profile.npy"), profile)
    np.save(os.path.join(output_dir, "profile_indices.npy"), indices)
    np.save(os.path.join(output_dir, "anomaly_indices.npy"), anomalies)

    # Save metadata
    metadata = {{
        "method": method,
        "window_size": window_size,
        "normalize": normalize,
        "threshold": float(threshold),
        "threshold_percentile": {threshold_percentile},
        "num_anomalies": int(len(anomalies)),
        "data_length": int(ts.shape[0] if ts.ndim == 1 else ts.shape[-1]),
    }}
    with open(os.path.join(output_dir, "metadata.json"), "w") as f:
        json.dump(metadata, f, indent=2)

    result = {{
        "type": "completed",
        "bestModelPath": os.path.join(output_dir, "matrix_profile.npy"),
        "lastModelPath": None,
        "resultsDir": output_dir,
    }}
    print("ANNOTIX_EVENT:" + json.dumps(result), flush=True)

if __name__ == "__main__":
    main()
"#,
        model_id = model_id,
        header = sp.header,
        window_size = window_size,
        normalize = py_bool(normalize),
        threshold_percentile = threshold_percentile,
    )
}

fn generate_export_section(formats: &[String]) -> String {
    if formats.is_empty() {
        return "# No export formats requested".to_string();
    }

    let mut lines = vec![
        "    # Export model to requested formats".to_string(),
        "    exported = []".to_string(),
        format!("    best = YOLO(best_model) if os.path.exists(best_model) else model"),
    ];

    for fmt in formats {
        lines.push(format!(
            "    try:\n        export_path = best.export(format=\"{fmt}\")\n        exported.append({{\"format\": \"{fmt}\", \"path\": str(export_path)}})\n    except Exception as e:\n        print(f\"Warning: export to {fmt} failed: {{e}}\", file=sys.stderr)",
            fmt = fmt,
        ));
    }

    lines.push("    result[\"exportedModels\"] = exported".to_string());
    lines.join("\n")
}

