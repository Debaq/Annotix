/// Genera los archivos del entrenamiento para un backend.
///
/// Es el único lugar que traduce el contrato del dataset a rutas concretas: pide al
/// `PreparedDataset` exactamente las claves que el backend consume y falla aquí —
/// con un mensaje que dice qué falta y qué sí hay— en vez de escribir un `train.py`
/// que moriría con `FileNotFoundError` a mitad del entrenamiento.
///
/// Devuelve pares `(nombre de archivo, contenido)`.
pub fn generate_train_script_for_backend(
    req: &TrainingRequest,
    ds: &PreparedDataset,
) -> Result<Vec<(String, String)>, String> {
    /// Claves que consume cada familia de backend.
    const COCO: &[&str] = &[
        keys::IMAGES_TRAIN,
        keys::ANN_TRAIN,
        keys::IMAGES_VAL,
        keys::ANN_VAL,
    ];
    const MASKS: &[&str] = &[
        keys::IMAGES_TRAIN,
        keys::MASKS_TRAIN,
        keys::IMAGES_VAL,
        keys::MASKS_VAL,
    ];
    const CLASSIFY: &[&str] = &[
        keys::IMAGES_TRAIN,
        keys::LABELS_JSON_TRAIN,
        keys::IMAGES_VAL,
        keys::LABELS_JSON_VAL,
    ];
    const TS_SUPERVISED: &[&str] = &[keys::X_TRAIN, keys::Y_TRAIN, keys::X_VAL, keys::Y_VAL];

    let one = |name: &str, content: String| Ok(vec![(name.to_string(), content)]);

    match req.backend {
        // Ultralytics consume su data.yaml; el resto de rutas las resuelve el propio yaml.
        TrainingBackend::Yolo => {
            let data = ultralytics_data_arg(ds, &req.task)?;
            let config = yolo_config_from_request(req);
            one("train.py", generate_train_script(&config, &data))
        }
        TrainingBackend::RtDetr => {
            // RT-DETR sólo hace detección: siempre data.yaml.
            let data = ultralytics_data_arg(ds, &req.task)?;
            one("train.py", generate_rtdetr_script(req, &data))
        }
        TrainingBackend::RfDetr => {
            let sp = ds.script_paths(COCO)?;
            one("train.py", generate_rfdetr_script(req, &sp))
        }
        TrainingBackend::HfDetection => {
            let sp = ds.script_paths(COCO)?;
            one("train.py", generate_hf_detection_script(req, &sp))
        }
        TrainingBackend::Smp => {
            let sp = ds.script_paths(MASKS)?;
            one("train.py", generate_smp_script(req, &sp))
        }
        TrainingBackend::HfSegmentation => {
            let mut needed = MASKS.to_vec();
            needed.push(keys::CLASSES_FILE);
            let sp = ds.script_paths(&needed)?;
            one("train.py", generate_hf_seg_script(req, &sp))
        }
        TrainingBackend::HfInstance => {
            let sp = ds.script_paths(COCO)?;
            one("train.py", generate_hf_instance_script(req, &sp))
        }
        TrainingBackend::HfPose => {
            let sp = ds.script_paths(COCO)?;
            one("train.py", generate_hf_pose_script(req, &sp))
        }
        TrainingBackend::Timm => {
            let sp = ds.script_paths(CLASSIFY)?;
            one("train.py", generate_timm_script(req, &sp))
        }
        TrainingBackend::HfClassification => {
            let mut needed = CLASSIFY.to_vec();
            needed.push(keys::CLASSES_FILE);
            let sp = ds.script_paths(&needed)?;
            one("train.py", generate_hf_classification_script(req, &sp))
        }
        TrainingBackend::Tsai => {
            let sp = ds.script_paths(TS_SUPERVISED)?;
            one("train.py", generate_tsai_script(req, &sp))
        }
        TrainingBackend::PytorchForecasting => {
            let sp = ds.script_paths(&[keys::LONG_CSV])?;
            one("train.py", generate_pytorch_forecasting_script(req, &sp))
        }
        TrainingBackend::Pyod => {
            let sp = ds.script_paths(&[keys::X_TRAIN, keys::X_VAL])?;
            one("train.py", generate_pyod_script(req, &sp))
        }
        TrainingBackend::Tslearn => {
            let sp = ds.script_paths(&[keys::X_TRAIN])?;
            one("train.py", generate_tslearn_script(req, &sp))
        }
        TrainingBackend::Pypots => {
            let sp = ds.script_paths(&[keys::X_TRAIN, keys::X_VAL])?;
            one("train.py", generate_pypots_script(req, &sp))
        }
        TrainingBackend::Stumpy => {
            let sp = ds.script_paths(&[keys::X_TRAIN])?;
            one("train.py", generate_stumpy_script(req, &sp))
        }
        TrainingBackend::Sklearn => {
            let sp = ds.script_paths(&[keys::TABLE_CSV, keys::TABLE_META])?;
            one("train.py", generate_sklearn_script(req, &sp))
        }
    }
}

